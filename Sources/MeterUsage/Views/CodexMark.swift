/// The pixel-mascot silhouette used for Claude in the menu bar, drawn as a
/// shape so it can be tinted by status colour. This is the same mascot
/// ClaudeWatch uses for Claude.
struct ClaudeMascotShape: Shape {
    func path(in r: CGRect) -> Path {
        var p = Path()
        func block(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ rad: CGFloat = 0) {
            let rect = CGRect(x: r.minX + r.width * x, y: r.minY + r.height * y,
                              width: r.width * w, height: r.height * h)
            if rad > 0 {
                p.addRoundedRect(in: rect, cornerSize: CGSize(width: r.width * rad, height: r.width * rad))
            } else {
                p.addRect(rect)
            }
        }
        block(0.08, 0.10, 0.84, 0.60, 0.16)   // head
        block(0.16, 0.66, 0.11, 0.22)          // legs
        block(0.35, 0.66, 0.11, 0.24)
        block(0.54, 0.66, 0.11, 0.24)
        block(0.73, 0.66, 0.11, 0.22)
        block(0.27, 0.28, 0.15, 0.20)          // eyes (cut out via even-odd)
        block(0.58, 0.28, 0.15, 0.20)
        return p
    }
}

